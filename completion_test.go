package main

import (
	"bytes"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"testing"

	"github.com/spf13/cobra"
)

func TestShellQueryCompletionTransport(t *testing.T) {
	if runtime.GOOS == "windows" {
		t.Skip("shell integration uses Unix shells")
	}
	for _, shell := range []string{"bash", "zsh", "fish"} {
		t.Run(shell, func(t *testing.T) {
			executable, err := exec.LookPath(shell)
			if err != nil {
				t.Skip(shell + " is not installed")
			}
			root := &cobra.Command{Use: "app"}
			var generated bytes.Buffer
			var script string
			switch shell {
			case "bash":
				err = generateBashCompletion(root, &generated)
				script = `
source "$1"
app() {
 [[ "$#" == 4 && "$4" == '.items[] | {name, email: .em' ]] || return 1
 printf '%s\tstring\n:6\n' '.items[] | {name, email: .email'
}
words=(app run -q "'.items[] | {name, email: .em'")
cur="${words[3]}"
__app_get_completion_results
[[ "$directive" == 6 ]] || exit 2
printf '%s\n' "$out"
`
			case "zsh":
				err = root.GenZshCompletion(&generated)
				script = `
compdef() { :; }
source "$1"
app() {
 [[ "$#" == 4 && "$4" == '.items[] | {name, email: .em' ]] || return 1
 printf '%s\tstring\n:6\n' '.items[] | {name, email: .email'
}
_describe() { print -r -- "${completions[@]}"; }
words=(app run -q "'.items[] | {name, email: .em'")
CURRENT=4
_app
`
			case "fish":
				err = root.GenFishCompletion(&generated, true)
				script = `
source $argv[1]
function app
 printf '%s\tstring\n:6\n' '.items[] | {name, email: .email'
end
complete -C "app run -q '.items[] | {name, email: .em"
`
			}
			if err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(t.TempDir(), "completion")
			if err := os.WriteFile(path, generated.Bytes(), 0600); err != nil {
				t.Fatal(err)
			}
			command := exec.Command(executable, "-c", script, "test", path)
			out, err := command.CombinedOutput()
			if err != nil {
				t.Fatalf("%s: %v\n%s", shell, err, out)
			}
			if !strings.Contains(string(out), ".email") || !strings.Contains(string(out), "name, email") {
				t.Fatalf("lost query punctuation: %s", out)
			}
		})
	}
}
